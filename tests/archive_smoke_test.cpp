/// Copie d'une fixture dans un vecteur.
Bytes Copy(const unsigned char* data, size_t size) {
	return Bytes(data, data + size);
}

std::span<const uint8_t> AsBytes(const char* text) {
	return std::span<const uint8_t>(reinterpret_cast<const uint8_t*>(text), std::strlen(text));
}

size_t FindSequence(const Bytes& haystack, const char* needle) {
	size_t length = std::strlen(needle);
	for (size_t i = 0; i + length <= haystack.size(); ++i)
		if (std::memcmp(haystack.data() + i, needle, length) == 0)
			return i;
	return haystack.size();
}

String Hex(std::span<const uint8_t> bytes) {
	String out;
	for (uint8_t byte : bytes)
		out.Concat(String::Format("%02x", byte));
	return out;
}

/// Données compressibles mais non triviales (texte pseudo-aléatoire).
Bytes SampleData(size_t size, uint32_t seed = 1) {
	Bytes data(size);
	uint32_t state = seed;
	for (size_t i = 0; i < size; ++i) {
		state = state * 1664525u + 1013904223u;
		data[i] = uint8_t("abcdefgh \n0123"[(state >> 24) % 14]);
	}
	return data;
}

