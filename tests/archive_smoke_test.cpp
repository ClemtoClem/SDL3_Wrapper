TEST(VirtualFs, ImplicitDirectoriesAndNavigator) {
	VirtualFs fs;
	ASSERT_TRUE(fs.AddFile("a/b/c.txt", Bytes{'c'}).IsOk());
	ASSERT_TRUE(fs.AddFile("a/d.txt", Bytes{'d'}).IsOk());
	ASSERT_TRUE(fs.Find("a/b").IsSome());
	EXPECT_TRUE(fs.Get(fs.Find("a/b").Unwrap()).implicit);
	EXPECT_TRUE(fs.AddFile("a/b", Bytes{}).IsError()); // conflit fichier/dossier
	EXPECT_EQ(fs.FileCount(), size_t(2));

	Navigator nav(fs);
	ASSERT_TRUE(nav.ChangeDirectory("a/b").IsOk());
	EXPECT_EQ(nav.Cwd(), "/a/b");
	ASSERT_TRUE(nav.ChangeDirectory("../").IsOk());
	EXPECT_EQ(nav.Cwd(), "/a");
	EXPECT_EQ(nav.List().size(), size_t(2));
	EXPECT_TRUE(nav.Resolve("b/c.txt").IsSome());
	EXPECT_TRUE(nav.Resolve("/a/d.txt").IsSome());
	EXPECT_TRUE(nav.ChangeDirectory("d.txt").IsError());
	EXPECT_TRUE(nav.ChangeDirectory("../../..").IsError());
	EXPECT_EQ(nav.Glob("**/*.txt").size(), size_t(2));
}

