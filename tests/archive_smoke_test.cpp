TEST(Codecs, Bzip2ZstdPpmdRoundTripsInChunks) {
	const Bytes data = SampleData(300000, 9);
	// Écriture par morceaux de tailles variées, lecture par morceaux.
	auto encode = [&data](auto open) {
		auto target = std::make_shared<Bytes>();
		auto encoder = open(OpenMemorySink(target).Unwrap());
		for (size_t at = 0, step = 1; at < data.size(); at += step, step = step * 7 % 65521 + 1) {
			const size_t take = std::min(step, data.size() - at);
			EXPECT_TRUE(
				StreamWrite(encoder, std::span<const uint8_t>(data.data() + at, take)).IsOk());
		}
		EXPECT_TRUE(FinishStream(encoder).IsOk());
		return std::move(*target);
	};
	auto decode = [](Result<ArchiveStream, ArchiveError> stream) {
		Bytes out;
		uint8_t chunk[777];
		for (;;) {
			auto got = StreamRead(stream.Value(), chunk, sizeof(chunk));
			if (got.IsError() || got.Value() == 0)
				break;
			out.insert(out.end(), chunk, chunk + got.Value());
		}
		return out;
	};
	const Bytes bz =
		encode([](ArchiveStream sink) { return OpenBzip2Encoder(std::move(sink), 5).Unwrap(); });
	EXPECT_TRUE(bz.size() < data.size() / 2);
	EXPECT_TRUE(decode(OpenBzip2Stream(OpenMemoryStream(bz).Unwrap())) == data);
	const Bytes zs =
		encode([](ArchiveStream sink) { return OpenZstdEncoder(std::move(sink), 3).Unwrap(); });
	EXPECT_TRUE(zs.size() <
				data.size() * 6 / 10); // texte aléatoire de 14 symboles : ~3,8 bits par octet
	EXPECT_TRUE(decode(OpenZstdStream(OpenMemoryStream(zs).Unwrap())) == data);
	const Bytes pp = encode([](ArchiveStream sink) {
		return OpenPpmd7Encoder(std::move(sink), 6, 16u << 20).Unwrap();
	});
	EXPECT_TRUE(decode(OpenPpmd7Stream(OpenMemoryStream(pp).Unwrap(), 6, 16u << 20, data.size())) ==
				data);

	// Données altérées : erreur, jamais de données fausses rendues en silence.
	Bytes broken = zs;
	broken[broken.size() / 2] ^= 0x10;
	auto corrupt = ZstdDecompress(broken);
	EXPECT_TRUE(corrupt.IsError() || corrupt.Value() != data);
	EXPECT_TRUE(Bzip2Decompress(Bytes(bz.begin(), bz.begin() + long(bz.size() / 2))).IsError());
}

