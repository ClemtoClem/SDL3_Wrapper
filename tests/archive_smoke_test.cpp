TEST(Lzma, XzFixtureFromLiblzmaAndRoundTrips) {
	auto fixture = XzDecompress(Copy(XZ_FIXTURE, sizeof(XZ_FIXTURE)));
	ASSERT_TRUE(fixture.IsOk());
	EXPECT_EQ(fixture.Value().size(), GBA_SIZE);
	EXPECT_TRUE(Crc32(fixture.Value()) == GBA_CRC);

	const Bytes data = SampleData(50000, 9);
	LzmaProperties props;
	auto raw = LzmaDecompress(LzmaCompress(data, props, 5, true), props, UINT64_MAX);
	ASSERT_TRUE(raw.IsOk());
	EXPECT_TRUE(raw.Value() == data);
	auto lzma2 = Lzma2Decompress(Lzma2Compress(data, 1u << 20, 5), 1u << 20);
	ASSERT_TRUE(lzma2.IsOk());
	EXPECT_TRUE(lzma2.Value() == data);
	auto xz = XzCompress(data, 5, 1u << 20, XzCheck::SHA256);
	ASSERT_TRUE(xz.IsOk());
	auto back = XzDecompress(xz.Value());
	ASSERT_TRUE(back.IsOk());
	EXPECT_TRUE(back.Value() == data);
	// Plafond de taille et corruption.
	EXPECT_TRUE(XzDecompress(xz.Value(), 1000).IsError());
	Bytes corrupt = xz.Value();
	corrupt[corrupt.size() / 2] ^= 0x10;
	EXPECT_TRUE(XzDecompress(corrupt).IsError());
}

TEST(Filters, BranchConvertersAreReversible) {
	Bytes code = SampleData(4096, 5);
	for (size_t i = 0; i + 8 < code.size(); i += 97) { // appels et sauts plausibles
		code[i] = 0xE8;
		code[i + 4] = 0x00;
	}
	for (auto convert : {BcjX86, BcjArm, BcjArmThumb, BcjArm64}) {
		Bytes filtered = code;
		convert(filtered, true);
		convert(filtered, false);
		EXPECT_TRUE(filtered == code);
	}
	Bytes encoded = code;
	BcjX86(encoded, true);
	EXPECT_FALSE(encoded == code); // le filtre a réellement converti des adresses
	Bytes delta = code;
	DeltaEncode(delta, 4);
	DeltaDecode(delta, 4);
	EXPECT_TRUE(delta == code);
}

