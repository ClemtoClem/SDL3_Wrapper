TEST(Crypto, Aes256Fips197) {
	uint8_t key[32];
	for (int i = 0; i < 32; ++i)
		key[i] = uint8_t(i);
	const uint8_t plain[16] = {0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
							   0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff};
	auto aes = Aes::Create(std::span<const uint8_t>(key, 32));
	ASSERT_TRUE(aes.IsOk());
	uint8_t cipher[16], back[16];
	aes.Value().EncryptBlock(plain, cipher);
	EXPECT_EQ(Hex(cipher), "8ea2b7ca516745bfeafc49904b496089");
	aes.Value().DecryptBlock(cipher, back);
	EXPECT_TRUE(std::memcmp(back, plain, 16) == 0);
	EXPECT_TRUE(Aes::Create(std::span<const uint8_t>(key, 20)).IsError());
}

TEST(Crypto, ShaHmacPbkdf2) {
	Sha256 sha;
	sha.Update(AsBytes("abc"));
	EXPECT_EQ(Hex(sha.Final()), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
	Sha1 sha1;
	sha1.Update(AsBytes("abc"));
	EXPECT_EQ(Hex(sha1.Final()), "a9993e364706816aba3e25717850c26c9cd0d89d");
	// RFC 2202, cas 2.
	Hmac<Sha1> hmac(AsBytes("Jefe"));
	hmac.Update(AsBytes("what do ya want for nothing?"));
	EXPECT_EQ(Hex(hmac.Final()), "effcdf6ae5eb2fa2d27416d5f184df9c259a7c79");
	// RFC 6070, 2 itérations.
	EXPECT_EQ(Hex(Pbkdf2HmacSha1(AsBytes("password"), AsBytes("salt"), 2, 20)),
			  "ea6c014dc72d6f8ccd1ed92ace1d41f0d8de8957");
	auto random = SecureRandomBytes(32);
	ASSERT_TRUE(random.IsOk());
	EXPECT_EQ(random.Value().size(), size_t(32));
}

