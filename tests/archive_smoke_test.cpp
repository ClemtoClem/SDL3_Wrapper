/// Relit une archive écrite et compare chaque fichier à l'arbre d'origine.
void ExpectSameTree(const VirtualFs& expected, Archive& archive, bool withSymlinks) {
	for (VirtualFs::NodeId id : expected.Flatten()) {
		const VirtualFs::Node& node = expected.Get(id);
		Option<VirtualFs::NodeId> found = archive.Fs().Find(node.info.path);
		if (node.info.type == EntryType::SYMLINK && !withSymlinks)
			continue;
		ASSERT_TRUE(found.IsSome());
		const VirtualFs::Node& read = archive.Fs().Get(found.Unwrap());
		EXPECT_TRUE(read.info.type == node.info.type);
		if (node.IsFile()) {
			auto bytes = archive.Read("/" + node.info.path);
			ASSERT_TRUE(bytes.IsOk());
			EXPECT_TRUE(bytes.Value() == node.content);
		} else if (node.info.type == EntryType::SYMLINK) {
			EXPECT_EQ(read.info.linkTarget, node.info.linkTarget);
		}
	}
}

